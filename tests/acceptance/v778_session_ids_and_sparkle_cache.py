#!/usr/bin/env python3
"""v778 — a failed generate catalog must not hide every ✨, and the Control deck
must show the A-id a session ALREADY has (RH-20).

Operator, verbatim: *"io non vedo nulla di cio che dici nella scheda subagents"* and
*"Some sessions not recognized in control page for example one without number? Isnt
autogenerated that number on creation? … Diagnose why not recognized"*.

Two separate defects, both measured live on 2026-11-03:

1. `api()` never throws — a 401/404 comes back as `{error: …}` — so the old
   `loadGenSurfaces()` cached an EMPTY map for the whole life of the tab and every
   ✨ silently disappeared with it. The server was serving the markup all along
   (3 × `subDraftHost`, 1 × `subagent.new` in the served HTML) and the same page
   mounted the control at 431 CSS px once the catalog was re-fetched.
2. A session IS born with its `A<n>` (`memory.stores.ensure_agent`), yet the Control
   deck rendered "—" for it: the deck builds its roster from `/api/agents/tree`,
   which deliberately EXCLUDES identity records (`kind="session"`), and it threw
   away the `agent` field `/api/orbit/sessions` already carries.

Deterministic: source contracts only. No browser, no server, no model.

RH-22 (section D) adds the other half of the same contract: a backend write of
`config/subagents.yaml` — A1's `webui.configure target='subagents'`, the CLI, the Orbit
deck — must reach the panel, which is only a VIEW of that file.
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UI = open(os.path.join(REPO, "webui", "index.html"), encoding="utf-8").read()
SW = open(os.path.join(REPO, "webui", "sw.js"), encoding="utf-8").read()
DECK = open(os.path.join(REPO, "src", "longrun", "orbit", "web", "orbit.html"),
            encoding="utf-8").read()
REG = open(os.path.join(REPO, "src", "longrun", "orbit", "registry.py"),
           encoding="utf-8").read()
AGENTS = open(os.path.join(REPO, "src", "longrun", "agent", "agents.py"),
              encoding="utf-8").read()
STORES = open(os.path.join(REPO, "src", "longrun", "memory", "stores.py"),
              encoding="utf-8").read()
results = []


def check(name, ok, detail=""):
    results.append(bool(ok))
    print(("PASS " if ok else "FAIL ") + name + ((" :: " + str(detail)[:300]) if detail and not ok else ""))


# ---------------------------------------------------------------- A. the ✨ catalog
_A = UI[UI.find("async function loadGenSurfaces(force)"):]
_A = _A[:_A.find("\n}") + 2] if "\n}" in _A else _A
check("A1 a failed/empty catalog is NOT cached (the next mount retries)",
      "if (!rows.length) return _genSurfaces || {};" in _A
      and "_genSurfaces = {};" in _A,
      _A[:200])
check("A2 the poisoned cache is gone: no assignment before the empty check",
      _A.find("if (!rows.length)") < _A.find("_genSurfaces = {};")
      and "let d = {};" not in _A)
check("A3 the surface lookup is unchanged for the caller",
      "function genSurface(id) { return (_genSurfaces || {})" in UI
      and 'mountSparkle($("subDraftHost"), "subagent.new"' in UI)

# ------------------------------------------------------------- B. the shell version
check("B1 the service worker's shell cache is bumped past v3 (RH-18/RH-19 changed it)",
      'const CACHE = "longrun-shell-v4";' in SW
      and 'const CACHE = "longrun-shell-v3";' not in SW)
check("B2 the bump is documented as a rule, not as a one-off",
      "BUMP THIS WHENEVER THE SHELL CHANGES" in SW)

# ------------------------------------------------- C. the A-id a session already has
check("C1 the orbit roster publishes the agent id",
      '"agent": _agent_id(sid)' in REG)
check("C2 every session is born with its A<n>",
      'reg.designate(sid, name=title or None, kind="session")' in STORES
      and "def ensure_agent(sess)" in STORES)
check("C3 the org chart stays team-only (an identity is not a membership)",
      'if a.get("kind") != "session"' in AGENTS)
check("C4 the deck's plain-session row carries the id it was throwing away",
      "agent: s.agent || null" in DECK)
check("C5 the id cell falls back to that id instead of printing a dash",
      "const aid = a.id || a.agent || null;" in DECK and "esc(aid)" in DECK)
check("C6 the dash now means 'no record at all', not 'not designated'",
      'title="no agent record for this session"' in DECK
      and "plain session — not designated as an agent yet" not in DECK)
check("C7 the ⋮ opener and the AI badge follow the same id",
      'data-aid="' in DECK and 'esc(aid || "")' in DECK
      and "(aid && this.written)" in DECK)
check("C8 the shared opener resolves an identity-only row",
      "x.id === aid || x.agent === aid" in DECK)

# --------------------------------- D. a BACKEND write must reach the panel (RH-22) ---
# Operator: *"io volevo agissero a livello di backend creando oggetti … e poi come
# conseguenza il frontend si aggiornasse sincronizzandosi col backend"*. The panel is a
# VIEW of `config/subagents.yaml`, which A1 (`webui.configure target='subagents'`), the
# CLI and the Orbit deck can write without ever touching this tab.
check("D1 'settings.changed' / 'config.saved' go through the ONE feed table",
      '"settings.changed": ev => { scheduleDiagnosticsRefresh(); subagentsSyncFromBackend(ev); },' in UI
      and '"config.saved": ev => { scheduleDiagnosticsRefresh(); subagentsSyncFromBackend(ev); },' in UI)
check("D2 the sync is guarded: its own file, visible panel, no pending save, nobody typing",
      'if (f && f !== "subagents.yaml") return;' in UI
      and "if (_subSaveTimer) return;" in UI
      and "if (ae && panel.contains(ae)) return;" in UI
      and "loadSubagents();" in UI)
check("D3 the debounce id is cleared when it FIRES, so the guard can tell",
      "_subSaveTimer = setTimeout(() => { _subSaveTimer = 0; saveSubagents(false); }, 700);" in UI)
check("D4 those kinds are not subscribed twice (one table, not two)",
      UI.count("es.addEventListener(kind, scheduleDiagnosticsRefresh)") == 1
      and '"config.saved", "providers.update"' not in UI)

print("\n---\nv778: %d/%d PASS" % (sum(results), len(results)))
sys.exit(0 if all(results) else 1)
