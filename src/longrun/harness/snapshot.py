#!/usr/bin/env python3
"""Freeze one matched input tree for a confined whole-run probe.

A probe only means something when the reference and every candidate start from
the SAME bytes. This module builds that package once (code, config, skills,
rules, workspace) and freezes it read-only; a candidate is a hardlinked variant
of the same package with an explicitly declared delta. The manifest records a
SHA256 per file plus one digest, so a run can prove what it consumed instead of
trusting a mutable checkout.

Layout of one package (mounted read-only at /input):

    src/            the harness code actually executed
    config/         tools/routing/providers/compaction configuration
    skills/         the skill tree the prompt sees
    rules/          global + project rule text (applied through rules.append)
    workspace/      the starting workspace copy
    manifest.json   goal, model, port, per-file hashes, digest

Sources: Docker read-only bind mounts
(https://docs.docker.com/reference/cli/docker/container/run/#read-only).
"""
import hashlib
import json
import os
import shutil
import stat
import subprocess
import uuid

from longrun.tools import sandbox

DEFAULTS = {"max_mb": 256, "port": 18080}
SKIP_DIRS = {".git", "node_modules", ".venv", "__pycache__", ".gradle", "build",
             "dist", ".mypy_cache", ".pytest_cache", ".ruff_cache", "target"}
SKIP_SUFFIX = (".pyc", ".pyo")
CONFIG_FILES = ("tools.yaml", "compaction.yaml", "hooks.yaml", "decisions.yaml",
                "subagents.yaml", "trace_policy.yaml", "index.yaml", "embedding.yaml")
DELTA_PREFIXES = ("rules/", "skills/harness/")


def _safe_rel(rel):
    rel = str(rel or "").replace("\\", "/")
    if (not rel or rel.startswith("/") or ".." in rel.split("/")
            or "\0" in rel or os.path.isabs(rel)):
        return None
    return rel


def _hash(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _walk(root):
    for base, dirs, names in os.walk(root, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(names):
            if name.endswith(SKIP_SUFFIX):
                continue
            path = os.path.join(base, name)
            if os.path.islink(path) or not os.path.isfile(path):
                continue
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            if rel == "manifest.json":
                continue
            yield rel, path


def files_of(root):
    """{relative path: sha256} for every regular file in a package."""
    return {rel: _hash(path) for rel, path in _walk(root)}


def digest_of(files):
    """One digest over the sorted per-file hashes."""
    body = "\n".join("%s %s" % (rel, files[rel]) for rel in sorted(files))
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


class _Budget:
    def __init__(self, max_mb):
        self.limit = max(0, int(max_mb)) * 1024 * 1024
        self.used = 0

    def add(self, size):
        self.used += int(size)
        return self.used <= self.limit


def _copy_tree(src, dst, budget):
    """Copy regular files under `src`; never follow or copy external symlinks."""
    root = os.path.realpath(src or "")
    if not os.path.isdir(root):
        return True  # an absent optional tree (e.g. no skills) is not an error
    for rel, path in _walk(root):
        try:
            size = os.path.getsize(path)
        except OSError:
            continue
        if not budget.add(size):
            return False
        out = os.path.join(dst, rel)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        shutil.copy2(path, out)
    return True


def _write(path, text, budget):
    data = str(text).encode("utf-8")
    if not budget.add(len(data)):
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    return True


def _quoted(value):
    return json.dumps(str(value))


def _providers(model, port, context_length):
    return "\n".join([
        "# Generated by harness.snapshot: one fixed, keyless gateway model.",
        'version: "1"',
        "env_files: []",
        "default: %s" % _quoted("h2:" + str(model)),
        "providers:",
        "  - id: h2",
        "    name: Harness2 gateway",
        "    kind: openai",
        "    base_url: http://127.0.0.1:%d/v1" % int(port),
        "    local: true",
        "    models:",
        "      - {id: %s, context_length: %d}" % (_quoted(model), int(context_length)),
        "",
    ])


def _routing(model):
    ref = _quoted("h2:" + str(model))
    roles = ("chat", "agent", "subagent", "summarizer", "team_lead",
             "team_member", "longrun_agent")
    lines = ["# Generated by harness.snapshot: every role uses the fixed model.", "roles:"]
    for role in roles:
        lines += ["  %s:" % role, "    model: %s" % ref]
    lines += ["default_fallbacks: []", "quota_cooldown: false", ""]
    return "\n".join(lines)


def _apply_rules_text():
    """The rule owner, imported lazily so a headless build stays cheap."""
    from longrun.memory import rules
    return rules


def build(base, c=None, model=None, port=None, context_length=32768):
    """Freeze one package. Returns {"ok", "path", "digest", "files", "refusals"}."""
    c = c or {}
    base = base or {}
    model = str(model or base.get("model") or "").strip()
    port = int(port or c.get("port") or DEFAULTS["port"])
    workspace = str(base.get("workspace") or "").strip()
    if not model:
        return {"ok": False, "reason": "a probe needs one fixed model"}
    if not workspace or not os.path.isdir(workspace):
        return {"ok": False, "reason": "no workspace to freeze"}
    path = sandbox.reserve_whole_run()
    budget = _Budget(c.get("max_mb") or DEFAULTS["max_mb"])
    try:
        module = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        src = os.path.dirname(module)
        repo = os.path.dirname(src)
        if not _copy_tree(os.path.join(repo, "src"), os.path.join(path, "src"), budget):
            raise RuntimeError("source tree exceeds the snapshot bound")
        os.makedirs(os.path.join(path, "config"), exist_ok=True)
        for name in CONFIG_FILES:
            source = os.path.join(repo, "config", name)
            if os.path.isfile(source):
                with open(source, "rb") as f:
                    text = f.read().decode("utf-8", "replace")
                if not _write(os.path.join(path, "config", name), text, budget):
                    raise RuntimeError("config exceeds the snapshot bound")
        if not _write(os.path.join(path, "config", "providers.yaml"),
                      _providers(model, port, context_length), budget):
            raise RuntimeError("providers config exceeds the snapshot bound")
        if not _write(os.path.join(path, "config", "routing.yaml"),
                      _routing(model), budget):
            raise RuntimeError("routing config exceeds the snapshot bound")
        from longrun.memory import skills as skills_mod
        if not _copy_tree(getattr(skills_mod, "SKILLS_DIR", ""),
                          os.path.join(path, "skills"), budget):
            raise RuntimeError("skills exceed the snapshot bound")
        rules = _apply_rules_text()
        collected = rules.collect(ws=workspace)
        rules_text = {}
        for scope in ("global", "project"):
            texts = []
            for name in collected[scope]["files"]:
                if scope == "project" and name == rules.project_agents_path(workspace):
                    continue
                with open(name, encoding="utf-8", errors="replace") as f:
                    texts.append(f.read())
            rules_text[scope] = "\n\n".join(texts)
        os.makedirs(os.path.join(path, "rules"), exist_ok=True)
        if not _write(os.path.join(path, "rules", "snapshot.json"),
                      json.dumps(rules_text, ensure_ascii=True, sort_keys=True), budget):
            raise RuntimeError("rules exceed the snapshot bound")
        if not _copy_tree(workspace, os.path.join(path, "workspace"), budget):
            raise RuntimeError("workspace exceeds the snapshot bound")
        files = files_of(path)
        manifest = {"goal": str(base.get("goal") or ""), "model": model,
                    "port": port, "created": _now(),
                    "source": {"repo_head": _head(repo)},
                    "digest": digest_of(files), "files": files}
        with open(os.path.join(path, "manifest.json"), "w", encoding="utf-8") as f:
            json.dump(manifest, f, ensure_ascii=True, sort_keys=True)
        _freeze(path)
        return {"ok": True, "path": path, "digest": manifest["digest"],
                "files": files, "manifest": manifest}
    except Exception as exc:  # noqa: BLE001
        remove(path)
        return {"ok": False, "reason": "%s: %s" % (type(exc).__name__, exc)}


def variant(source_path, delta):
    """Hardlink a package, then apply the declared delta (the ONLY difference)."""
    source_path = os.path.abspath(str(source_path or ""))
    if not os.path.isfile(os.path.join(source_path, "manifest.json")):
        return {"ok": False, "reason": "source package is not a snapshot"}
    applied = []
    for rel, text in (delta or {}).items():
        clean = _safe_rel(rel)
        if clean is None or not clean.startswith(DELTA_PREFIXES):
            return {"ok": False, "reason": "delta path is not allowed: %r" % (rel,)}
        applied.append((clean, str(text)))
    path = sandbox.reserve_whole_run()
    try:
        for base, dirs, names in os.walk(source_path):
            rel_dir = os.path.relpath(base, source_path)
            target_dir = path if rel_dir == "." else os.path.join(path, rel_dir)
            os.makedirs(target_dir, exist_ok=True)
            for name in names:
                source = os.path.join(base, name)
                target = os.path.join(target_dir, name)
                try:
                    os.link(source, target)
                except OSError:
                    shutil.copy2(source, target)
        for rel, text in applied:
            target = os.path.join(path, rel)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            if os.path.exists(target):
                os.unlink(target)
            with open(target, "w", encoding="utf-8") as f:
                f.write(text)
        with open(os.path.join(source_path, "manifest.json"), encoding="utf-8") as f:
            source_manifest = json.load(f)
        files = files_of(path)
        manifest = dict(source_manifest)
        manifest.update({"digest": digest_of(files), "files": files,
                         "variant": {"source": os.path.basename(
                             os.path.dirname(source_path)), "delta": [r for r, _ in applied]}})
        manifest_path = os.path.join(path, "manifest.json")
        if os.path.exists(manifest_path):
            os.unlink(manifest_path)  # hardlinked: never rewrite the source package
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, ensure_ascii=True, sort_keys=True)
        _freeze(path)
        return {"ok": True, "path": path, "digest": manifest["digest"],
                "files": files, "delta": [r for r, _ in applied]}
    except Exception as exc:  # noqa: BLE001
        remove(path)
        return {"ok": False, "reason": "%s: %s" % (type(exc).__name__, exc)}


def verify(path):
    """Re-hash a package and compare it with its own manifest."""
    try:
        with open(os.path.join(path, "manifest.json"), encoding="utf-8") as f:
            manifest = json.load(f)
    except (OSError, ValueError):
        return {"ok": False, "reason": "manifest is unreadable"}
    files = files_of(path)
    digest = digest_of(files)
    return {"ok": digest == manifest.get("digest") and files == manifest.get("files"),
            "digest": digest, "expected": manifest.get("digest")}


def remove(path):
    """Delete one package; refuses anything that is not one of our reservations."""
    root = os.path.realpath(sandbox.registry.workspace_dir())
    target = os.path.realpath(str(path or ""))
    token = os.path.basename(os.path.dirname(target))
    if (os.path.basename(target) != "inputs" or os.path.dirname(os.path.dirname(target)) != root
            or not token.startswith("h2-") or len(token) != 35
            or any(c not in "0123456789abcdef" for c in token[3:])):
        return {"ok": False, "reason": "not a reserved snapshot path"}
    for base, dirs, names in os.walk(target):
        for name in dirs + names:
            try:
                os.chmod(os.path.join(base, name), stat.S_IRWXU)
            except OSError:
                pass
    try:
        os.chmod(target, stat.S_IRWXU)
    except OSError:
        pass
    shutil.rmtree(os.path.dirname(target), ignore_errors=True)
    return {"ok": not os.path.exists(target)}


def _freeze(path):
    for _rel, full in _walk(path):
        try:
            os.chmod(full, stat.S_IRUSR)
        except OSError:
            pass
    try:
        os.chmod(os.path.join(path, "manifest.json"), stat.S_IRUSR)
    except OSError:
        pass


def _now():
    import time
    return round(time.time(), 3)


def _head(repo):
    try:
        import subprocess
        out = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=5)
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:  # noqa: BLE001
        return ""


def new_id():
    return "probe-" + uuid.uuid4().hex
